use std::fs;
use std::hint::black_box;
use std::io;
use std::time::Instant;

use soul_t0_benchkit::{fixture_metadata_jsonl, fixture_scale, score_all_t0};

fn main() -> io::Result<()> {
    let manifest_dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let fixtures = soul_t0_benchkit::all_fixtures();
    fs::write(
        manifest_dir.join("fixtures/cases.jsonl"),
        fixture_metadata_jsonl(&fixtures),
    )?;

    let scale = fixture_scale();
    for _ in 0..10 {
        black_box(score_all_t0(black_box(&scale.interactions)));
    }

    const ITERATIONS: u128 = 200;
    let started = Instant::now();
    let mut observed_peers = 0usize;
    for _ in 0..ITERATIONS {
        let scores = score_all_t0(black_box(&scale.interactions));
        observed_peers = black_box(scores.len());
    }
    let elapsed = started.elapsed();
    assert_eq!(observed_peers, 200);

    let total_ns = elapsed.as_nanos();
    let ns_per_scale_score = total_ns / ITERATIONS;
    let ns_per_interaction = total_ns / (ITERATIONS * scale.interactions.len() as u128);
    let bench = format!(
        "# T0 microbenchmark\n\
         \n\
         Generated by `cargo run --release --bin benchkit` using `std::time::Instant`.\n\
         This is a deterministic microbenchmark, not Criterion.\n\
         \n\
         - Fixture: F_SCALE\n\
         - Input: {} interactions across 200 peers\n\
         - Timed scoring passes: {ITERATIONS}\n\
         - Total elapsed: {:.3} ms\n\
         - Time per full F_SCALE scoring operation: {ns_per_scale_score} ns/op\n\
         - Amortized time per input interaction: {ns_per_interaction} ns/interaction\n\
         - Output peers per pass: {observed_peers}\n\
         \n\
         The timing includes fresh aggregation and allocation for every pass. It excludes fixture\n\
         construction, warm-up, JSONL serialization, and file I/O. Results are machine-specific.\n",
        scale.interactions.len(),
        elapsed.as_secs_f64() * 1_000.0,
    );
    fs::write(manifest_dir.join("BENCH.md"), bench)?;

    println!("wrote fixtures/cases.jsonl and BENCH.md ({ns_per_scale_score} ns/op)");
    Ok(())
}
