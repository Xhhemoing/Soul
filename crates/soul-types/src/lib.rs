//! The public read boundary. No Session, storage, Tauri or HTTP dependencies.

#![forbid(unsafe_code)]

use serde::{Deserialize, Serialize};
use ts_rs::TS;

mod writes;
pub use writes::*;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[serde(deny_unknown_fields)]
pub struct RuntimeStatus {
    pub wizard_completed: bool,
    pub store_opened: bool,
    /// An allowlisted protection label; never a path or provider exception.
    pub key_protection: String,
    pub config_problem: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[cfg_attr(feature = "openapi", derive(utoipa::IntoParams))]
#[cfg_attr(feature = "openapi", into_params(parameter_in = Query))]
#[serde(deny_unknown_fields)]
pub struct PeoplePageRequest {
    #[serde(default = "default_people_limit")]
    #[cfg_attr(feature = "openapi", param(minimum = 1, maximum = 100, default = 50))]
    #[cfg_attr(feature = "openapi", schema(minimum = 1, maximum = 100, default = 50))]
    pub limit: u32,
    #[serde(default)]
    #[cfg_attr(
        feature = "openapi",
        param(minimum = 0, maximum = 1000000, default = 0)
    )]
    #[cfg_attr(
        feature = "openapi",
        schema(minimum = 0, maximum = 1000000, default = 0)
    )]
    pub offset: u32,
}

fn default_people_limit() -> u32 {
    50
}

impl Default for PeoplePageRequest {
    fn default() -> Self {
        Self {
            limit: default_people_limit(),
            offset: 0,
        }
    }
}

