/// Generated from the Rust DTO definitions, in dependency order.
pub fn typescript() -> String {
    let declarations = [
        RuntimeStatus::decl(),
        PeoplePageRequest::decl(),
        PersonView::decl(),
        PeoplePage::decl(),
        MemoryIdRequest::decl(),
        MemoryDetailView::decl(),
        ReadErrorCode::decl(),
        ReadErrorDetail::decl(),
        ReadError::decl(),
    ];
    let mut output = String::from("// Generated by soul-types. Do not edit by hand.\n\n");
    for declaration in declarations {
        output.push_str("export ");
        output.push_str(&declaration);
        output.push('\n');
    }
    for declaration in writes::declarations() {
        output.push_str("export ");
        output.push_str(&declaration);
        output.push('\n');
    }
    output
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        + "\n"
}
