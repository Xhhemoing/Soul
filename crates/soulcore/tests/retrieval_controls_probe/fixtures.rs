pub fn cases() -> Vec<Case> {
    let mut result = Vec::new();
    for (task_index, task) in tasks().into_iter().enumerate() {
        let mut base: Vec<_> = task
            .records
            .iter()
            .enumerate()
            .map(|(i, (title, summary))| Candidate {
                id: opaque(task_index, i),
                title: (*title).into(),
                summary: (*summary).into(),
            })
            .collect();
        for i in 8..14 {
            base.push(Candidate {
                id: opaque(task_index, i),
                title: format!("{}：其他阶段记录{i}", task.scope),
                summary: format!("历史档案第{i}项记录的是上一年度的资料整理流程，已经结束；仅描述当时如何登记文件，不约定此次沟通的行动、时间或许可。"),
            });
        }
        let duplicates: Vec<_> = (14..32)
            .map(|i| {
                let original = &base[[0, 4, 7][(i - 14) / 6]];
                Candidate {
                    id: opaque(task_index, i),
                    title: original.title.clone(),
                    summary: original.summary.clone(),
                }
            })
            .collect();
        for (condition_index, condition) in ["duplicate32", "compact14", "distinct32"]
            .into_iter()
            .enumerate()
        {
            let aliases = if condition == "compact14" {
                duplicates.clone()
            } else {
                vec![]
            };
            let mut candidates = base.clone();
            if condition == "duplicate32" {
                candidates.extend(duplicates.clone());
            }
            if condition == "distinct32" {
                candidates.extend(distractors(task_index).iter().enumerate().map(
                    |(offset, (title, summary, _))| Candidate {
                        id: opaque(task_index, 14 + offset),
                        title: (*title).into(),
                        summary: (*summary).into(),
                    },
                ));
            }
            // One fixed permutation, independent of relevance and strategy.
            candidates.sort_by_key(|c| (c.id.bytes().map(usize::from).sum::<usize>() * 19) % 41);
            let sources: Vec<_> = candidates.iter().chain(&aliases).collect();
            let facts = task
                .facts
                .iter()
                .enumerate()
                .map(|(i, (description, indices, reason))| Fact {
                    id: format!("f{i}"),
                    description,
                    acceptable_source_ids: sources
                        .iter()
                        .filter(|source| {
                            indices.iter().any(|index| {
                                source.title == base[*index].title
                                    && source.summary == base[*index].summary
                            })
                        })
                        .map(|source| source.id.clone())
                        .collect(),
                    reason,
                })
                .collect::<Vec<_>>();
            let mut supporting = Vec::new();
            let mut inapplicable = Vec::new();
            for source in &sources {
                if facts
                    .iter()
                    .any(|f| f.acceptable_source_ids.contains(&source.id))
                {
                    continue;
                }
                if source.id == base[3].id || source.id == base[6].id {
                    supporting.push((
                        source.id.clone(),
                        "提供被替代安排或沟通背景，但必要事实已有完整有效来源",
                    ));
                } else {
                    let exclusion = if condition == "distinct32" {
                        (14..32)
                            .position(|index| source.id == opaque(task_index, index))
                            .map(|offset| distractors(task_index)[offset].2)
                    } else {
                        None
                    };
                    inapplicable.push((
                        source.id.clone(),
                        exclusion.unwrap_or(
                            "适用对象、阶段或事项不同，或仅为广告指令，不提供本任务必要事实",
                        ),
                    ));
                }
            }
            result.push(Case {
                input: InputCase {
                    case_id: format!("q{:02}", task_index * 3 + condition_index),
                    task: TaskInput {
                        scope: task.scope.into(),
                        intent: task.intent.into(),
                        constraints: task.constraints.into(),
                    },
                    candidates,
                },
                task_index,
                condition,
                aliases,
                facts,
                supporting,
                inapplicable,
            });
        }
    }
    result
}

pub fn fact_coverage(facts: &[Fact], selected: &[String]) -> usize {
    facts
        .iter()
        .filter(|fact| {
            fact.acceptable_source_ids
                .iter()
                .any(|id| selected.contains(id))
        })
        .count()
}
